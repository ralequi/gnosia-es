def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Apply the first manual ES-over-EN translation batch.")
    parser.add_argument(
        "--source-manifest",
        type=Path,
        default=OUTPUT_DIR / "manifest.json",
        help="Snapshot manifest with the original English slot.",
    )
    parser.add_argument(
        "--work-dir",
        type=Path,
        default=WORK_DIR,
        help="Tracked work corpus directory.",
    )
    parser.add_argument(
        "--force-init",
        action="store_true",
        help="Recreate the work directory from the source snapshot before applying translations.",
    )
    return parser.parse_args()


def initialize_work(source_manifest: Path, work_dir: Path, force: bool) -> None:
    if work_dir.exists() and not force:
        return

    if work_dir.exists():
        shutil.rmtree(work_dir)

    manifest = read_json(source_manifest)
    source_base = source_manifest.parent
    ensure_dir(work_dir / ENTITY_JSON_DIRNAME)
    for entry in manifest["entities"]:
        src = source_base / entry["file"]
        dst = work_dir / entry["file"]
        ensure_dir(dst.parent)
        shutil.copy2(src, dst)

    manifest = dict(manifest)
    manifest["translation_target_language"] = "es"
    manifest["translation_overrides_slot"] = "en"
    manifest["translation_source_manifest"] = str(source_manifest.resolve())
    write_json(work_dir / "manifest.json", manifest)


def translate_text(entity_name: str, sheet_name: str, source_text: str) -> str:
    def lookup(candidate: str) -> str | None:
        context_key = (entity_name, sheet_name, candidate)
        if context_key in CONTEXT_TRANSLATIONS:
            return CONTEXT_TRANSLATIONS[context_key]
        if candidate in TUTORIAL_TRANSLATIONS:
            return TUTORIAL_TRANSLATIONS[candidate]
        if candidate in TUTORIAL_TRANSLATIONS_V2:
            return TUTORIAL_TRANSLATIONS_V2[candidate]
        if candidate in MANUAL_TRANSLATIONS_V2:
            return MANUAL_TRANSLATIONS_V2[candidate]
        if candidate in OVERRIDE_TRANSLATIONS:
            return OVERRIDE_TRANSLATIONS[candidate]
        if candidate in GLOSSARY_TRANSLATIONS:
            return GLOSSARY_TRANSLATIONS[candidate]
        if candidate in EXACT_TRANSLATIONS:
            return EXACT_TRANSLATIONS[candidate]
        return None

    candidates = [source_text]
    try:
        decoded = codecs.decode(source_text, "unicode_escape")
    except UnicodeDecodeError:
        decoded = source_text
    if decoded not in candidates:
        candidates.append(decoded)

    for candidate in candidates:
        translated = lookup(candidate)
        if translated is not None:
            if "\\n" in source_text or '\\"' in source_text:
                return json.dumps(translated, ensure_ascii=False)[1:-1]
            return translated

    return source_text


def main() -> int:
    args = parse_args()
    initialize_work(args.source_manifest, args.work_dir, args.force_init)
    manifest = read_json(args.work_dir / "manifest.json")

    changed = 0
    touched_entities = 0
    for entry in manifest["entities"]:
        entity_path = args.work_dir / entry["file"]
        payload = read_json(entity_path)
        entity_name = payload["entity_name"]
        if entity_name not in PHASE1_ENTITIES:
            continue

        entity_changed = False
        for sheet in payload["sheets"]:
            sheet_name = sheet["name"]
            for param in sheet["params"]:
                texts = param["texts"]
                if len(texts) < 2:
                    continue
                source_text = texts[1]
                translated = translate_text(entity_name, sheet_name, source_text)
                if translated != source_text:
                    texts[1] = translated
                    changed += 1
                    entity_changed = True

        if entity_changed:
            write_json(entity_path, payload)
            touched_entities += 1

    print(f"Manual phase-1 batch applied: {changed} strings updated across {touched_entities} entities.")
    return 0


