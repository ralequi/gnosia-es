def load_glossary_translations() -> dict[str, str]:
    payload = read_json(GLOSSARY_PATH)
    translations: dict[str, str] = {}
    for section in ("roles", "acciones", "estado_y_ui"):
        section_payload = payload.get(section, {})
        for source_text, translated_text in section_payload.items():
            translations[str(source_text)] = str(translated_text)
    return translations


